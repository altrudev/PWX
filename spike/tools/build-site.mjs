#!/usr/bin/env node
// Builds the files for a hosted PWX demo on an ordinary static host (Apache or LiteSpeed with
// .htaccess), the same files and headers server/serve.mjs sends in production mode.
//   node tools/build-site.mjs https://pwx.altru.dev [outDir]
// Output:
//   <out>/loader/  -> document root of the loader host (pwx.altru.dev)
//   <out>/apps/    -> document root shared by every app host (app1..app4.pwx.altru.dev)
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(import.meta.url), "../..");
const [loaderUrl, out = join(ROOT, "dist/site")] = process.argv.slice(2);
if (!/^https:\/\/[a-z0-9.-]+$/.test(loaderUrl ?? "")) throw new Error("usage: build-site.mjs https://loader.host [outDir]");
const host = new URL(loaderUrl).host;
const APPS = Array.from({ length: 4 }, (_, i) => `https://app${i + 1}.${host}`);   // same rule as loader.mjs
const L = join(out, "loader"), A = join(out, "apps");
rmSync(out, { recursive: true, force: true });
for (const d of [L, join(L, "lib"), join(L, "packages"), A, join(A, "__pwx")]) mkdirSync(d, { recursive: true });
const cp = (from, to) => copyFileSync(join(ROOT, from), to);

// ---------- loader host ----------
for (const f of ["index.html", "loader.mjs", "loader.css", "store.mjs", "config.mjs", "sw.js"]) cp(`loader/${f}`, join(L, f));
cp("lib/pwx-verify.mjs", join(L, "lib/pwx-verify.mjs"));
cp("local/release.json", join(L, "loader-release.json"));
for (const p of ["notes"]) cp(`packages/${p}.pwx.json`, join(L, "packages", `${p}.pwx.json`));
const loaderCsp = `default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self'; frame-src ${APPS.join(" ")}; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'`;
writeFileSync(join(L, ".htaccess"), `# PWX demo loader (${host}). Generated by tools/build-site.mjs; do not edit by hand.
# This is the front door of the PWX demo: it verifies apps and runs each one on its own app host.
Options -Indexes
DirectoryIndex index.html
<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "no-referrer"
  Header always set Cross-Origin-Opener-Policy "same-origin"
  Header always set Content-Security-Policy "${loaderCsp}"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), usb=(), serial=(), hid=(), bluetooth=(), payment=()"
</IfModule>
<FilesMatch "\\.mjs$">
  ForceType text/javascript
</FilesMatch>
<FilesMatch "^(sw\\.js)$">
  <IfModule mod_headers.c>
    Header set Cache-Control "max-age=86400"
  </IfModule>
</FilesMatch>
<FilesMatch "\\.(html|mjs|css|json)$">
  <IfModule mod_headers.c>
    Header set Cache-Control "no-store"
  </IfModule>
</FilesMatch>
RewriteEngine On
# Only package files are served from packages/, never anything else in that folder.
RewriteRule ^packages/(?![a-z0-9-]+\\.pwx\\.json$) - [F,L]
# Never serve signing keys, hidden files or this file.
RewriteRule (^|/)\\. - [F,L]
RewriteRule (^|/)[^/]*key[^/]*\\.json$ - [F,L]
`);

// ---------- app hosts (one folder for app1..app4) ----------
for (const f of ["bootstrap.html", "bootstrap.js", "guard.js", "renderer.js", "strict.html", "ui.css"]) cp(`app-origin/${f}`, join(A, "__pwx", f));
cp("lib/pwx-verify.mjs", join(A, "__pwx", "verify.mjs"));
const appSw = readFileSync(join(ROOT, "app-origin/sw.js"), "utf8");
if (!appSw.includes("__PWX_LOADER_ORIGIN__") || !appSw.includes("__PWX_TEST__")) throw new Error("app-origin/sw.js placeholders missing");
writeFileSync(join(A, "sw.js"), appSw.replace("__PWX_LOADER_ORIGIN__", loaderUrl).replace("__PWX_TEST__", "0"));
writeFileSync(join(A, "index.html"), `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>PWX demo: app storage area</title>
<style>body{font:17px/1.5 system-ui,sans-serif;max-width:560px;margin:48px auto;padding:0 20px;color:#222}a{color:#1a5fb4}</style>
</head><body>
<h1>This is a private storage area for a PWX app</h1>
<p>This address is part of the <a href="${loaderUrl}/">PWX demo</a>. Each app you open there gets its own
address like this one, so apps can't read each other's data. There's nothing to see here directly.</p>
<p><a href="${loaderUrl}/">Go to the PWX demo</a> &middot; <a href="https://github.com/altrudev/PWX">About PWX on GitHub</a></p>
</body></html>
`);
const STRICT_CSP = `default-src 'none'; script-src 'self'; worker-src data:; img-src blob:; style-src 'self'; font-src 'none'; connect-src 'none'; frame-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors ${loaderUrl}`;
writeFileSync(join(A, ".htaccess"), `# PWX demo app hosts (app1-app4.${host}). Generated by tools/build-site.mjs; do not edit by hand.
# Each app opened in the demo loader (${loaderUrl}) runs on one of these addresses, so every app
# gets its own private browser storage. Only the PWX runtime is served here; app files come from
# the verified copy the loader installs.
Options -Indexes
DirectoryIndex index.html
<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "no-referrer"
</IfModule>
RewriteEngine On
# PWX pages open only inside the loader's frame (or for this host's own service worker), never as
# a tab: browsers send Sec-Fetch-Dest "document" for a tab.
RewriteCond %{HTTP:Sec-Fetch-Dest} !^iframe$
RewriteCond %{HTTP:Sec-Fetch-Dest}%{HTTP:Sec-Fetch-Site} !^emptysame-origin$
RewriteRule ^__pwx/(bootstrap\\.html|strict) - [F,L]
# Only the runtime, the service worker and the info page exist here.
RewriteRule ^__pwx/(bootstrap\\.html|bootstrap\\.js|verify\\.mjs|guard\\.js|renderer\\.js|strict\\.html|ui\\.css)$ - [L]
RewriteRule ^(sw\\.js|index\\.html)?$ - [L]
RewriteRule ^ - [R=404,L]
<FilesMatch "^bootstrap\\.html$">
  Header set Content-Security-Policy "default-src 'self'; script-src 'self'; frame-ancestors ${loaderUrl}"
</FilesMatch>
<FilesMatch "^strict\\.html$">
  Header set Content-Security-Policy "${STRICT_CSP}"
</FilesMatch>
<FilesMatch "\\.mjs$">
  ForceType text/javascript
</FilesMatch>
<FilesMatch "^sw\\.js$">
  Header set Service-Worker-Allowed "/"
  Header set Cache-Control "max-age=86400"
</FilesMatch>
<FilesMatch "\\.(html|js|mjs|css)$">
  Header set Cache-Control "no-store"
</FilesMatch>
<FilesMatch "^sw\\.js$">
  Header set Cache-Control "max-age=86400"
</FilesMatch>
`);
console.log(`built ${out}: loader for ${loaderUrl}, app hosts ${APPS.join(", ")}`);
