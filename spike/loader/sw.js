// Loader service worker (hosted tier). Keeps the loader on the device so installed apps launch
// with no network, and decides which loader code runs:
//  - The loader's files come from a release signed with the PWX release key pinned below.
//  - Every file is checked against that signed release each time it is served, so a changed
//    cache entry is replaced from the network or refused, never run.
//  - Updates happen only when the user asks: a newer signed release, every file verified, then
//    switched in one step. Older versions and same-version swaps are refused.
// What this can't stop: the browser itself re-fetches this file from the host. A host that
// changes sw.js can change everything. The loader page warns when that happens (loader.mjs),
// and the Verified tier (pwx-local) removes the host from the picture.
// BEGIN PINNED LOADER (generated by tools/pin-runtime.mjs; do not edit by hand)
const RELEASE_KEY = "YuCRSgEJ89t+8Xn8AOqQcxz2zk+hNMpI1R61VA1OStY=";
// END PINNED LOADER
const META = "pwx-loader-meta", RELEASE_URL = "/__pwx/loader-release";
const SHELL = { "/": "loader/index.html", "/loader.mjs": "loader/loader.mjs", "/loader.css": "loader/loader.css",
  "/store.mjs": "loader/store.mjs", "/config.mjs": "loader/config.mjs", "/lib/pwx-verify.mjs": "lib/pwx-verify.mjs" };
// App origins follow from the loader's own address, so the same signed files work on any host:
//   test host  http://127.0.0.1:8100 -> http://127.0.0.1:8110 ... :8129 (20 origins)
//   real host  https://pwx.example   -> https://app1.pwx.example ... app4 (one subdomain each)
const APPS = (self.location.hostname === "127.0.0.1"
  ? Array.from({ length: 20 }, (_, i) => `http://127.0.0.1:${8110 + i}`)
  : Array.from({ length: 4 }, (_, i) => `${self.location.protocol}//app${i + 1}.${self.location.host}`)).join(" ");
const CSP = `default-src 'self'; script-src 'self'; style-src 'self'; connect-src 'self'; frame-src ${APPS}; object-src 'none'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'`;
const TYPES = { html: "text/html; charset=utf-8", mjs: "text/javascript", css: "text/css" };
const headersFor = (file) => ({ "Content-Type": TYPES[file.split(".").pop()], ...(file.endsWith(".html") ? { "Content-Security-Policy": CSP } : {}) });

// ---------- release verification (same rules as lib/pwx-verify.mjs, inlined: classic worker) ----------
const b64dec = (s) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));
const b64enc = (u) => { let s = ""; for (const b of new Uint8Array(u)) s += String.fromCharCode(b); return btoa(s); };
const canon = (v) => Array.isArray(v) ? `[${v.map(canon).join(",")}]`
  : v && typeof v === "object" ? `{${Object.keys(v).sort().map((k) => JSON.stringify(k) + ":" + canon(v[k])).join(",")}}`
  : JSON.stringify(v);
const hash = async (buf) => "sha256-" + b64enc(await crypto.subtle.digest("SHA-256", buf));
const VERSION_RE = /^\d{1,9}\.\d{1,9}\.\d{1,9}$/;
const cmpVersion = (a, b) => { const x = a.split(".").map(Number), y = b.split(".").map(Number); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] < y[i] ? -1 : 1; return 0; };

async function verifyRelease(text) {
  const doc = JSON.parse(text);
  const { release, sig } = doc ?? {};
  if (!release || !sig || sig.alg !== "ed25519" || sig.key !== RELEASE_KEY) throw new Error("release is not signed with the PWX release key");
  if (!VERSION_RE.test(release.version ?? "")) throw new Error("release version is malformed");
  for (const file of Object.values(SHELL)) if (!/^sha256-[A-Za-z0-9+/]{43}=$/.test(release.files?.[file] ?? "")) throw new Error(`release has no hash for ${file}`);
  const key = await crypto.subtle.importKey("raw", b64dec(RELEASE_KEY), { name: "Ed25519" }, false, ["verify"]);
  const ok = await crypto.subtle.verify({ name: "Ed25519" }, key, b64dec(sig.sig), new TextEncoder().encode(canon(release)));
  if (!ok) throw new Error("release signature is invalid");
  return release;
}

// ---------- the installed release ----------
// META holds which version is current; each version's files and its signed release text live in
// their own cache. The release text is re-verified each time it's loaded, so a changed cache
// entry can't swap in different hashes.
let currentMemo = null;
function current() {
  return (currentMemo ??= (async () => {
    const meta = await (await caches.open(META)).match("current");
    if (!meta) throw new Error("no loader release installed");
    const { cache } = await meta.json();
    const text = await (await (await caches.open(cache)).match(RELEASE_URL))?.text();
    if (!text) throw new Error("installed release is missing");
    return { cache, release: await verifyRelease(text) };
  })().catch((err) => { currentMemo = null; throw err; }));
}

async function fetchRelease() {
  const res = await fetch("/loader-release.json", { cache: "no-store" });
  if (!res.ok) throw new Error(`no loader release on the host (HTTP ${res.status})`);
  const text = await res.text();
  return { text, release: await verifyRelease(text) };
}

// Fetch every file, check it against the signed release, and only then switch versions.
async function installRelease({ text, release }) {
  const name = "pwx-loader-" + release.version;
  await caches.delete(name);
  const c = await caches.open(name);
  try {
    for (const [path, file] of Object.entries(SHELL)) {
      const res = await fetch(path, { cache: "no-store" });
      const body = await res.arrayBuffer();
      if (!res.ok || (await hash(body)) !== release.files[file]) throw new Error(`${file} doesn't match the signed release`);
      await c.put(path, new Response(body));
    }
    await c.put(RELEASE_URL, new Response(text));
  } catch (err) { await caches.delete(name); throw err; }
  await (await caches.open(META)).put("current", new Response(JSON.stringify({ cache: name })));
  currentMemo = null;
  for (const k of await caches.keys()) if (k.startsWith("pwx-loader-") && k !== name && k !== META) await caches.delete(k);
}

async function serve(path) {
  const file = SHELL[path];
  let cur;
  try { cur = await current(); } catch (err) { return integrityError(String(err.message)); }
  const c = await caches.open(cur.cache);
  let body = await (await c.match(path))?.arrayBuffer();
  if (!body || (await hash(body)) !== cur.release.files[file]) {
    // The stored copy is missing or changed: accept a network copy only if it matches the release.
    body = null;
    try {
      const res = await fetch(path, { cache: "no-store" });
      const b = await res.arrayBuffer();
      if (res.ok && (await hash(b)) === cur.release.files[file]) { body = b; await c.put(path, new Response(b)); }
    } catch {}
  }
  if (!body) return integrityError(`${file} doesn't match signed release ${cur.release.version}, and the host didn't provide a copy that does.`);
  return new Response(body, { headers: headersFor(file) });
}
const integrityError = (why) => new Response(
  `PWX loader integrity check failed.\n\n${why}\n\nNothing was run. Installed apps and their data are untouched.\n`,
  { status: 503, headers: { "Content-Type": "text/plain; charset=utf-8", "X-PWX-Integrity": "failed" } });

// ---------- lifecycle ----------
self.addEventListener("install", (e) => e.waitUntil((async () => {
  // A new sw.js keeps the release the user already has; only a first install fetches one.
  // If the kept release isn't signed with this sw.js's key, it's fetched and verified anew.
  const have = await current().then(() => true, () => false);
  if (!have) await installRelease(await fetchRelease());
  await self.skipWaiting();
})()));
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));

// The loader page asks; nothing here contacts the host on its own after install.
self.addEventListener("message", (e) => {
  const port = e.ports[0];
  if (!port) return;
  const reply = (m) => port.postMessage(m);
  const type = e.data?.type;
  e.waitUntil((async () => {
    try {
      const cur = await current();
      if (type === "status") return reply({ ok: true, version: cur.release.version, sw: cur.release.files["loader/sw.js"] ?? null });
      if (type !== "check-update" && type !== "apply-update") return reply({ ok: false, error: "unknown request" });
      const next = await fetchRelease();
      const order = cmpVersion(next.release.version, cur.release.version);
      if (order < 0) throw new Error(`the host offered an older version (${next.release.version}); you have ${cur.release.version}`);
      if (order === 0) {
        if (canon(next.release) !== canon(cur.release)) throw new Error(`the host offered different contents under the same version (${cur.release.version})`);
        return reply({ ok: true, upToDate: true, version: cur.release.version, sw: cur.release.files["loader/sw.js"] ?? null });
      }
      if (type === "check-update") return reply({ ok: true, available: next.release.version, sw: next.release.files["loader/sw.js"] ?? null });
      await installRelease(next);
      return reply({ ok: true, applied: next.release.version });
    } catch (err) { reply({ ok: false, error: String(err.message || err) }); }
  })());
});

self.addEventListener("fetch", (e) => {
  const u = new URL(e.request.url);
  if (e.request.method !== "GET" || u.origin !== self.location.origin) return;
  if (u.pathname === "/__pwx/mode") {
    e.respondWith(new Response('{"local":false}', { headers: { "Content-Type": "application/json" } }));
    return;
  }
  const path = e.request.mode === "navigate" ? "/" : u.pathname;
  if (!(path in SHELL)) return; // packages, the release file, test hooks: straight to the host
  if (e.request.mode === "navigate") currentMemo = null; // re-verify the release on every launch
  e.respondWith(serve(path));
});
