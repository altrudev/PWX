#!/usr/bin/env node
// Pins the PWX runtime: writes the SHA-256 of every runtime file into app-origin/sw.js, so the
// service worker can refuse any copy that doesn't match. Run after changing a runtime file
// (and before tools/make-release.mjs, which hashes sw.js too).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";
import { sha256, b64 } from "../lib/pwx-verify.mjs";

const ROOT = join(fileURLToPath(import.meta.url), "../..");
const FILES = { "/__pwx/bootstrap.html": "bootstrap.html", "/__pwx/bootstrap.js": "bootstrap.js",
  "/__pwx/verify.mjs": "../lib/pwx-verify.mjs",
  "/__pwx/strict.html": "strict.html", "/__pwx/renderer.js": "renderer.js",
  "/__pwx/guard.js": "guard.js", "/__pwx/ui.css": "ui.css" };
const pinned = {};
for (const [path, file] of Object.entries(FILES)) {
  pinned[path] = await sha256(new Uint8Array(readFileSync(join(ROOT, "app-origin", file))));
}
const swPath = join(ROOT, "app-origin/sw.js");
const sw = readFileSync(swPath, "utf8");
const block = /(\/\/ BEGIN PINNED RUNTIME[^\n]*\n)[\s\S]*?(\/\/ END PINNED RUNTIME)/;
if (!block.test(sw)) throw new Error("pin markers not found in sw.js");
writeFileSync(swPath, sw.replace(block, `$1const PINNED = ${JSON.stringify(pinned, null, 2)};\n$2`));
console.log(`pinned ${Object.keys(pinned).length} runtime files in app-origin/sw.js`);

// The hosted loader's service worker accepts loader releases signed with this key only.
const keyPath = join(process.env.PWX_KEYS ?? join(homedir(), ".config/pwx-dev"), "release-key.json");
const { x } = JSON.parse(readFileSync(keyPath, "utf8"));
const releaseKey = b64.enc(b64.dec(x.replace(/-/g, "+").replace(/_/g, "/") + "="));
const loaderSw = join(ROOT, "loader/sw.js");
const lsw = readFileSync(loaderSw, "utf8");
const lblock = /(\/\/ BEGIN PINNED LOADER[^\n]*\n)[\s\S]*?(\/\/ END PINNED LOADER)/;
if (!lblock.test(lsw)) throw new Error("pin markers not found in loader/sw.js");
writeFileSync(loaderSw, lsw.replace(lblock, `$1const RELEASE_KEY = ${JSON.stringify(releaseKey)};\n$2`));
console.log("pinned the release key in loader/sw.js");

// The public log the loader checks package receipts against (M4). The spike pins its dev log.
const { devTrust } = await import("../log/devlog.mjs");
writeFileSync(join(ROOT, "loader/log-trust.mjs"), `// The public log this loader checks package receipts against (M4, soft mode).
// Generated by tools/pin-runtime.mjs; do not edit by hand. This is the spike's development log:
// its witnesses aren't independent yet, so a receipt from it only tests the path.
export const LOG_TRUST = ${JSON.stringify(await devTrust(), null, 2)};
`);
console.log("pinned the dev log's keys in loader/log-trust.mjs");
